import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

#define variables
L = 6 #ft
RA = 170 #lb
RB = 410 #lb
P1 = 100 #lb
q1 = 120 #lb/ft
q2 = 120 #lb/ft

#2. x positions along the beam
x=np.linspace(0,L,500)

#3 define variable v
V=np.zeros_like(x)

#4create a for loop
for i in range(len(x)):
  if x[i]<2:
    V[i] = RA-q1*x[i]
  elif x[i]<4:
    V[i] = RA-q1*2-P1
  else:
    V[i]=RA-q1*2-P1+RB-q2*(x[i]-4)

plt.plot(x,V)
plt.fill_between(x,V,color='lightgreen')
plt.axhline(0,color='black')

plt.xlabel('Distance along beam (ft)')
plt.ylabel('Shear (lb)')
plt.title('Shear Diagram')
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

#create a moment diagram
#define variables
L = 6 #ft
RA = 170 #lb
RB = 410 #lb
P1 = 100 #lb
q1 = 120 #lb/ft
q2 = 120 #lb/ft

#define the variable M
M=np.zeros_like(x)

for i in range(len(x)):
  if x[i]<2:
    M[i] = (RA*x[i])-(q1*x[i]**2)/2
  elif x[i]<4:
    M[i] = (RA*x[i])-(q1*2*(x[i]-1))-(P1*(x[i]-2))
  else:
    M[i] = (RA*x[i])-(q1*2*(x[i]-1))-(P1*(x[i]-2))+(RB*(x[i]-4))-(q2*(x[i]-4)*((x[i]-4)/2))

plt.plot(x,M)
plt.fill_between(x,M,color='lightgreen')
plt.axhline(0,color='black')

plt.xlabel('Distance along beam (ft)')
plt.ylabel('Moment (lb-ft)')
plt.title('Moment Diagram')
plt.show()

